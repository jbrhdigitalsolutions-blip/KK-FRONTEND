import fs from "node:fs/promises";
import path from "node:path";
import { writeText } from "../fs-utils.mjs";

function esc(v){if(v==null)return"—";return String(v).replace(/\|/g,"\\|").replace(/\r?\n/g," ")}
function j(v){return JSON.stringify(v,null,2)}
async function readJson(file,fallback=null){try{return JSON.parse(await fs.readFile(file,"utf8"))}catch{return fallback}}
function uniq(xs){return[...new Set((xs||[]).filter(Boolean))]}
function top(xs,n){return(xs||[]).slice(0,n)}

function summarizeTokens(t={}){
  return{
    colors:top(t.colors,24),fontSizes:top(t.fontSizes,20),fontFamilies:top(t.fontFamilies,12),
    fontWeights:top(t.fontWeights,12),lineHeights:top(t.lineHeights,16),letterSpacing:top(t.letterSpacing,12),
    radii:top(t.radii,20),spacing:top(t.spacing,24),shadows:top(t.shadows,16),opacity:top(t.opacity,12)
  };
}
function summarizeInteraction(x){
  return{selector:x.selector,text:String(x.text||"").slice(0,120),before:x.before,hover:x.hover,focus:x.focus,active:x.active,evidence:x.evidence};
}
function summarizeScroll(s={}){
  return{maxScrollY:s.maxScrollY,points:s.points,candidates:(s.candidates||[]).slice(0,24).map(c=>({
    selector:c.selector,position:c.position,overflow:c.overflow,samples:(c.samples||[]).slice(0,5)
  }))};
}
function summarizeViewport(snapshot,vp){
  const styles=snapshot.styles||[];
  const key=(snapshot.elements||[]).filter(e=>{
    const st=styles[e.styleId]||{};
    return Boolean(
      e.interactive || /^h[1-6]$/.test(e.tag||"") ||
      ["header","nav","main","aside","footer","section","form","dialog"].includes(e.tag) ||
      ["navigation","main","banner","contentinfo","complementary","dialog","tablist"].includes(e.role||"") ||
      ["fixed","sticky"].includes(st.position) || ["img","svg","video"].includes(e.tag)
    );
  }).slice(0,260).map(e=>({
    selector:e.selector,parentSelector:e.parentSelector,tag:e.tag,role:e.role,accessibleName:e.accessibleName,
    text:String(e.text||"").slice(0,220),interactive:!!e.interactive,rect:e.rect,styleId:e.styleId,attrs:e.attrs,pseudo:e.pseudo
  }));
  return{name:vp.profile?.name,viewport:snapshot.viewport,screenshot:vp.screenshot,counts:snapshot.counts,keyElements:key,runtimeAnimations:(snapshot.runtimeAnimations||[]).slice(0,120)};
}

export async function writeDesignBlueprint({auditRoot,auditFile,outFile,title="Reference Frontend Design Blueprint"}){
  const audit=await readJson(auditFile);
  if(!audit)throw new Error(`Cannot read audit: ${auditFile}`);
  const sharedCss=await readJson(path.join(auditRoot,audit.sharedCssFile||"shared-css.json"),{});
  const routeInventory=await readJson(path.join(auditRoot,audit.routeInventoryFile||"route-inventory.json"),{});
  const assets=await readJson(path.join(auditRoot,audit.assets?.manifest||"assets/manifest.json"),[]);
  const technology=audit.technology||await readJson(path.join(auditRoot,"technology.json"),[]);
  const reps=audit.representativeRoutes||[];
  const anchors=new Set(),lines=[];

  lines.push(`# ${title}`,"");
  lines.push("> Primary coding-agent visual contract generated by KK-FRONTEND.");
  lines.push("> Exact raw JSON and captured screenshots are bundled beside this file inside `DESIGN-PACK/`.");
  lines.push("> Preserve target functionality, APIs, routes, authentication, permissions, data/state, business logic and integrations.");
  lines.push("> Reconstruct presentation from measured evidence; do not copy proprietary reference source code.","");

  lines.push("## 0. Mandatory Coding-Agent Workflow","");
  lines.push("1. Read this `DESIGN.md` completely before changing code.");
  lines.push("2. Read `PACK-MANIFEST.json` and the route/profile JSON referenced below before implementing each route.");
  lines.push("3. Inspect every bundled reference screenshot for the route before writing layout CSS.");
  lines.push("4. Preserve the target application's behavior; the reference is a presentation contract.");
  lines.push("5. Implement shared tokens/shell/primitives first, then route-specific surfaces.");
  lines.push("6. Apply `VERIFIED` measurements exactly where semantically applicable. Do not invent `UNAVAILABLE`, `RESTRICTED` or unobserved values.");
  lines.push("7. Recheck every route that consumes a changed shared component.");
  lines.push("8. Completion requires screenshot comparison at all captured anchors.","");

  lines.push("## 1. Coverage","");
  lines.push(`- Reference: \`${esc(audit.target)}\``);
  lines.push(`- Captured: ${esc(audit.capturedAt)}`);
  lines.push(`- Mode: **${esc(audit.mode)}**`);
  lines.push(`- Evidence: **${esc(audit.evidenceStatus)}**`);
  lines.push(`- Raw URLs discovered: ${esc(audit.coverage?.rawRoutesDiscovered)}`);
  lines.push(`- Design-route templates: ${esc(audit.coverage?.designRouteTemplates??audit.coverage?.canonicalRouteFamilies)}`);
  lines.push(`- Content instances collapsed: ${esc(audit.coverage?.contentInstancesCollapsed)}`);
  lines.push(`- Locale aliases collapsed: ${esc(audit.coverage?.localeAliasesCollapsed)}`);
  lines.push(`- Unique visual clusters: ${esc(audit.coverage?.uniqueVisualClusters)}`);
  lines.push(`- Deep representatives: ${esc(audit.coverage?.deepRepresentativesScanned)}`);
  lines.push(`- CSS breakpoints: ${(audit.coverage?.globalBreakpointsPx||[]).join(", ")}`,"");
  lines.push("### Fidelity boundary","");
  lines.push("`Blueprint Fast` records exact full evidence at selected mobile/tablet/desktop anchors and readable CSS breakpoint declarations. It does not prove every intermediate width, hidden/auth-gated state, or native Safari/iOS/Android rasterization.","");

  lines.push("## 2. Frontend Technology Signals","","| Technology | Evidence status | Signal |","|---|---|---|");
  for(const t of technology||[])lines.push(`| ${esc(t.name)} | ${esc(t.confidence)} | ${esc(t.evidence)} |`);
  lines.push("");

  lines.push("## 3. Global Design Contract","","### Breakpoints / media / container queries","```json");
  lines.push(j({breakpointsPx:sharedCss.breakpointsPx||audit.coverage?.globalBreakpointsPx||[],mediaQueries:uniq(sharedCss.mediaQueries),containerQueries:uniq(sharedCss.containerQueries),supportsQueries:uniq(sharedCss.supportsQueries)}));
  lines.push("```","","### Global CSS custom properties","```json",j(sharedCss.customProperties||{}),"```","");
  lines.push("### Font faces","```json",j(sharedCss.fontFaces||[]),"```","");
  lines.push("### Keyframes","```json",j(sharedCss.keyframes||[]),"```","");
  lines.push("### State CSS rules","Full exact list: `machine/shared-css.json`.","```json",j(top(sharedCss.pseudoStateRules,160)),"```","");

  lines.push("## 4. Design Route Templates","","| Template | Representative | Dynamic | Collapsed instances | Aliases |","|---|---|---:|---:|---:|");
  for(const r of routeInventory.routes||[]){
    lines.push(`| \`${esc(r.templateKey||r.canonicalPath||r.url)}\` | \`${esc(r.url)}\` | ${r.dynamicTemplate?"yes":"no"} | ${(r.instances||[]).length} | ${(r.aliases||[]).length} |`);
  }
  lines.push("","Full exact inventory: `machine/route-inventory.json`.","");

  lines.push("## 5. Route-by-Route Implementation Blueprint","");
  let n=0;
  for(const rep of reps){
    if(!rep.file)continue;
    const routeFile=path.join(auditRoot,rep.file),route=await readJson(routeFile);
    if(!route)continue;
    n++;
    const routeDir=path.dirname(routeFile),routeRel=rep.file.replaceAll("\\","/");
    lines.push(`### ${n}. \`${esc(route.templateKey||route.url)}\``,"");
    lines.push(`- Representative URL: \`${esc(route.url)}\``);
    lines.push(`- Visual cluster: ${esc(route.clusterId)}`);
    lines.push(`- Evidence: **${esc(route.evidenceStatus)}**`);
    lines.push(`- Dynamic template: ${route.dynamicTemplate?"yes":"no"}`);
    lines.push(`- Exact route JSON: \`${esc(routeRel)}\``);
    lines.push(`- Exact route CSS: \`${esc(path.posix.join(path.posix.dirname(routeRel),"route-css.json"))}\``,"");
    lines.push("#### Measured route tokens","```json",j(summarizeTokens(route.designTokens||{})),"```","");
    lines.push("#### Responsive contract","```json",j(route.breakpoints||{}),"```","");
    lines.push("#### Interaction feedback","```json",j(top(route.interactions,80).map(summarizeInteraction)),"```","");
    lines.push("#### Scroll / fixed / sticky","```json",j(summarizeScroll(route.scrollBehavior||{})),"```","");

    for(const vp of route.viewports||[]){
      if(!vp?.file)continue;
      const snap=await readJson(path.join(routeDir,vp.file));if(!snap)continue;
      const sum=summarizeViewport(snap,vp);if(sum.name)anchors.add(sum.name);
      const profileRel=path.posix.join(path.posix.dirname(routeRel),vp.file.replaceAll("\\","/"));
      lines.push(`#### Anchor: ${esc(sum.name)}`,"");
      lines.push(`- Exact viewport: **${esc(sum.viewport?.width)} × ${esc(sum.viewport?.height)}**`);
      lines.push(`- DPR: ${esc(sum.viewport?.dpr)}`);
      lines.push(`- Document: ${esc(sum.viewport?.scrollWidth)} × ${esc(sum.viewport?.scrollHeight)}`);
      lines.push(`- Horizontal overflow: ${esc(sum.viewport?.horizontalOverflow)}`);
      lines.push(`- Reference screenshot: \`${esc(vp.screenshot)}\``);
      lines.push(`- Exact profile JSON: \`${esc(profileRel)}\``,"");
      lines.push("Key visual/interactive geometry:","```json",j({counts:sum.counts,keyElements:sum.keyElements,runtimeAnimations:sum.runtimeAnimations}),"```","");
    }
  }

  const byType={};for(const a of assets||[])byType[a.type||"unknown"]=(byType[a.type||"unknown"]||0)+1;
  lines.push("## 6. Asset Contract","");
  lines.push(`- Design asset references inventoried: ${(assets||[]).length}`);
  lines.push(`- Download strategy: ${esc(audit.assets?.strategy||"unknown")}`);
  lines.push("- Exact asset URL/use/restriction inventory: `assets/manifest.json`.");
  lines.push("- Reuse exact reference assets only when authorized; otherwise use authorized project-owned equivalents while preserving measured geometry.","");
  lines.push("```json",j(byType),"```","");

  lines.push("## 7. Exact Machine Evidence Map","");
  lines.push("- `machine/reference-audit.json` — master scan record.");
  lines.push("- `machine/shared-css.json` — exact readable CSS/media/container/keyframe/state evidence.");
  lines.push("- `machine/route-inventory.json` — route-template discovery/collapse evidence.");
  lines.push("- `machine/route-coverage.json` — representative/cluster coverage mapping.");
  lines.push("- `machine/layout-clusters.json` — unique visual cluster grouping.");
  lines.push("- `routes/` — exact route JSON, profile JSON, route CSS, boundary data and screenshots.");
  lines.push("- `assets/manifest.json` — asset inventory/restriction evidence.","");

  lines.push("## 8. Acceptance Checklist","");
  lines.push("- [ ] Shared shell/navigation geometry matches every captured anchor.");
  lines.push("- [ ] Typography family/size/weight/line-height/letter-spacing matches.");
  lines.push("- [ ] Colors, surfaces, borders, radii, shadows, opacity, filters and backdrop effects match.");
  lines.push("- [ ] Buttons, fields, cards, menus, player controls and states match measured geometry.");
  lines.push("- [ ] Fixed/sticky/scroll behavior matches.");
  lines.push("- [ ] Mobile/tablet/desktop captured anchors match bundled screenshots.");
  lines.push("- [ ] Responsive media/container behavior follows measured CSS.");
  lines.push("- [ ] Animations/transitions/feedback match captured evidence.");
  lines.push("- [ ] Existing target functionality remains operational.");
  lines.push("- [ ] Visual comparison completed for every captured route template.","");

  lines.push("## 9. Machine Contract","```json");
  lines.push(j({schema:"kk-frontend-design-blueprint/v2",reference:audit.target,capturedAt:audit.capturedAt,scanMode:audit.mode,evidenceStatus:audit.evidenceStatus,anchors:[...anchors],breakpointsPx:audit.coverage?.globalBreakpointsPx||[],routeTemplateCount:audit.coverage?.designRouteTemplates??audit.coverage?.canonicalRouteFamilies,uniqueVisualClusters:audit.coverage?.uniqueVisualClusters,exactEvidenceRoot:"DESIGN-PACK",rule:"Implement VERIFIED evidence exactly; inspect referenced screenshots/JSON before each route; do not invent unavailable states."}));
  lines.push("```","","## 10. Known Restrictions","");
  for(const r of audit.restrictions||[])lines.push(`- ${esc(r)}`);
  lines.push("");

  const body=lines.join("\n");await writeText(outFile,body);
  return{outFile,bytes:Buffer.byteLength(body,"utf8"),routeSections:n,anchors:[...anchors]};
}
